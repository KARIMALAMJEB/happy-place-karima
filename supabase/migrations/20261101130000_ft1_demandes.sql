-- Lot 2 (FT1) : demandes enrichies, portées du prototype Happy Place V2.
-- Migration ADDITIVE : aucune colonne existante n'est modifiée ni supprimée, les valeurs par défaut
-- conservent le comportement actuel (toutes les demandes validées restent visibles par tous).
-- Les triggers de FT2 (notify_decision, record_submission_status, set_decision_info) ne sont pas touchés.
-- L'état « à compléter » du prototype = demande refusée avec le motif « à clarifier » (déjà présent en base).

-- 1. Nouveaux types
do $$ begin
  create type public.request_visibility as enum ('tous', 'equipe', 'manager');
exception when duplicate_object then null; end $$;

do $$ begin
  create type public.request_follow_up as enum ('ouvert', 'en_cours', 'resolu');
exception when duplicate_object then null; end $$;

-- 2. Nouvelles colonnes sur submissions
alter table public.submissions
  add column if not exists ref_number bigint generated by default as identity,
  add column if not exists title text,
  add column if not exists blocking boolean not null default false,
  add column if not exists visibility public.request_visibility not null default 'tous',
  add column if not exists theme text,
  add column if not exists confidential_identity boolean not null default false,
  add column if not exists validator_type text,
  add column if not exists follow_up public.request_follow_up,
  add column if not exists responsible text,
  add column if not exists target_date date,
  add column if not exists done boolean not null default false,
  add column if not exists clarifications jsonb not null default '[]'::jsonb,
  add column if not exists complement jsonb,
  add column if not exists reminded_at timestamptz;

alter table public.submissions
  drop constraint if exists submissions_validator_type_check,
  add constraint submissions_validator_type_check check (validator_type is null or validator_type in ('manager', 'admin')),
  drop constraint if exists submissions_title_check,
  add constraint submissions_title_check check (title is null or char_length(btrim(title)) between 3 and 120),
  drop constraint if exists submissions_theme_check,
  add constraint submissions_theme_check check (theme is null or theme in ('Conditions de travail', 'Cantine', 'CE', 'Informatique', 'Autre'));

-- Reprise de l'existant : un titre court tiré du contenu
update public.submissions
   set title = left(btrim(content), 80)
 where title is null;

-- 3. Équipe de l'utilisateur connecté (pour la visibilité « mon équipe »)
create or replace function private.current_team()
returns text
language sql
stable
security definer
set search_path to 'public', 'private'
as $$
  select au.team from public.allowed_users au where au.email = lower(auth.jwt() ->> 'email') limit 1
$$;

-- 4. Lecture : la visibilité choisie à l'envoi est appliquée par la base, pas seulement par l'écran
drop policy if exists "Allowed read submissions" on public.submissions;
create policy "Allowed read submissions" on public.submissions
  for select to authenticated
  using (
    private.is_allowed()
    and (
      private.is_admin()
      or (private.current_app_role() = 'manager'::public.app_role and private.can_review_team(team))
      or submitted_by_email = lower(auth.jwt() ->> 'email')
      or (
        status = 'validée'::public.submission_status
        and (
          visibility = 'tous'::public.request_visibility
          or (visibility = 'equipe'::public.request_visibility and lower(team) = lower(coalesce(private.current_team(), '')))
        )
      )
    )
  );

-- 5. Un manager peut désormais suivre l'exécution d'une demande validée de ses équipes
--    (suivi, responsable, date cible, terminée, relance) sans pouvoir toucher au reste.
create or replace function private.enforce_submission_review()
returns trigger
language plpgsql
security definer
set search_path to 'public', 'private'
as $function$
declare
  _suivi text[] := array['follow_up', 'responsible', 'target_date', 'done', 'reminded_at'];
begin
  if private.current_app_role() = 'manager'::public.app_role then
    -- cas 1 : suivi d'une demande déjà validée (seules les colonnes de suivi changent)
    if OLD.status = 'validée'::public.submission_status
       and NEW.status = OLD.status
       and private.can_review_team(OLD.team)
       and (to_jsonb(NEW) - _suivi) = (to_jsonb(OLD) - _suivi) then
      return NEW;
    end if;
    -- cas 2 : décision sur une demande en attente (règle d'origine)
    if NEW.author_name is distinct from OLD.author_name
       or NEW.team is distinct from OLD.team
       or NEW.content is distinct from OLD.content
       or NEW.created_at is distinct from OLD.created_at
       or NEW.status not in ('validée'::public.submission_status, 'refusée'::public.submission_status)
       or OLD.status <> 'en attente'::public.submission_status
       or not private.can_review_team(OLD.team) then
      raise exception 'Un manager peut uniquement valider ou refuser une soumission en attente de ses équipes, ou suivre une demande validée';
    end if;
  end if;
  return NEW;
end
$function$;

-- Policy de mise à jour manager : autorise aussi le suivi d'une demande validée
drop policy if exists "Managers review assigned submissions" on public.submissions;
create policy "Managers review assigned submissions" on public.submissions
  for update to authenticated
  using (
    private.current_app_role() = 'manager'::public.app_role
    and private.can_review_team(team)
    and status in ('en attente'::public.submission_status, 'validée'::public.submission_status)
  )
  with check (
    private.current_app_role() = 'manager'::public.app_role
    and private.can_review_team(team)
    and status in ('validée'::public.submission_status, 'refusée'::public.submission_status)
  );

-- 6. L'auteur complète sa demande après un refus « à clarifier » (RPC contrôlée, pas de droit d'écriture direct)
create or replace function public.complete_submission(_id uuid, _answers jsonb, _infos text default null)
returns void
language plpgsql
security definer
set search_path to 'public', 'private'
as $function$
declare
  _email text := lower(auth.jwt() ->> 'email');
begin
  if _email is null or not private.is_allowed() then
    raise exception 'Connexion requise.' using errcode = '42501';
  end if;
  update public.submissions
     set complement = jsonb_build_object(
           'reponses', coalesce(_answers, '[]'::jsonb),
           'infos', nullif(btrim(coalesce(_infos, '')), ''),
           'date', now()),
         status = 'en attente'::public.submission_status,
         rejection_category = null,
         rejection_note = null,
         decided_at = null,
         decided_by_name = null
   where id = _id
     and submitted_by_email = _email
     and status = 'refusée'::public.submission_status
     and rejection_category = 'à clarifier'::public.rejection_category;
  if not found then
    raise exception 'Cette demande ne peut pas être complétée.';
  end if;
end
$function$;

revoke all on function public.complete_submission(uuid, jsonb, text) from public, anon;
grant execute on function public.complete_submission(uuid, jsonb, text) to authenticated;
